-- ============================================================================
-- 121_consulting_admin_schema.sql
--
-- MY NUVOS admin panel (nuvosai.com/consulting/admin) — approved
-- 2026-10-26, "está excelente constrúyelo de manera real." Fills the 3
-- gaps flagged in the admin-panel design review (migration 119 has no
-- participant name, no payment/administrative status, no per-session
-- private notes, no objectives, and no session-report content):
--
--   - consulting_profiles: a participant's display name/company — the
--     investing app's user_profiles is deliberately never read by any
--     consulting_* table (see 119's header), so this is a SEPARATE,
--     minimal profile scoped only to Nuvos Consulting.
--   - consulting_payments: manual administrative/payment status per
--     enrollment. NOT a real billing integration (no Stripe here) — at
--     3-20 participants this is staff-tracked by hand, matching the
--     scale Diego described.
--   - consulting_objectives: the checklist shown in "Objetivos
--     educativos" (expediente section 2).
--   - consulting_private_notes: append-only instructor notes per
--     enrollment, distinct from a session's own notes field.
--   - consulting_session_reports: the editable Nuvos Session Report
--     draft generated by closing a session — reviewed and published by
--     staff, never auto-sent to the student. Publishing copies its
--     content into the session's own `notes` (what GET
--     /consulting/sessions/{id} already serves to the student) rather
--     than inventing a second student-facing read path.
--   - consulting_assignments gains a nullable enrollment_id: today an
--     assignment is only ever module-wide (assigned to everyone in that
--     module). Closing a session can assign a one-off exercise to just
--     that ONE student — module_id NULL + enrollment_id set marks that
--     case; module_id set (enrollment_id NULL) keeps the original
--     module-wide meaning unchanged.
--
-- Every new table: RLS enabled, no policy — same deny-all stance as
-- every other consulting_* table (service-role only, real enforcement
-- is the ownership/role check in app/api/routes/consulting_admin.py).
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS consulting_profiles (
  user_id    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name  TEXT NOT NULL,
  company    TEXT,
  role_title TEXT,
  phone      TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS consulting_payments (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  enrollment_id  UUID UNIQUE NOT NULL REFERENCES consulting_enrollments(id) ON DELETE CASCADE,
  status         TEXT NOT NULL DEFAULT 'al_dia' CHECK (status IN ('al_dia','atrasado','pendiente')),
  plan           TEXT DEFAULT 'monthly' CHECK (plan IN ('monthly','one_time')),
  next_charge_at DATE,
  notes          TEXT,
  updated_at     TIMESTAMPTZ DEFAULT NOW(),
  updated_by     UUID REFERENCES auth.users(id)
);

CREATE TABLE IF NOT EXISTS consulting_objectives (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  enrollment_id UUID NOT NULL REFERENCES consulting_enrollments(id) ON DELETE CASCADE,
  text          TEXT NOT NULL,
  achieved      BOOLEAN DEFAULT FALSE,
  order_index   INT DEFAULT 0,
  created_at    TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS consulting_private_notes (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  enrollment_id UUID NOT NULL REFERENCES consulting_enrollments(id) ON DELETE CASCADE,
  author_id     UUID REFERENCES auth.users(id),
  note          TEXT NOT NULL,
  created_at    TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS consulting_session_reports (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id           UUID UNIQUE NOT NULL REFERENCES consulting_sessions(id) ON DELETE CASCADE,
  enrollment_id        UUID NOT NULL REFERENCES consulting_enrollments(id) ON DELETE CASCADE,
  summary              TEXT,
  achievements         TEXT,
  strengths            TEXT,
  growth_areas         TEXT,
  next_assignment_text TEXT,
  status               TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
  created_at           TIMESTAMPTZ DEFAULT NOW(),
  published_at         TIMESTAMPTZ,
  published_by         UUID REFERENCES auth.users(id)
);

ALTER TABLE consulting_assignments ALTER COLUMN module_id DROP NOT NULL;
ALTER TABLE consulting_assignments ADD COLUMN IF NOT EXISTS enrollment_id UUID REFERENCES consulting_enrollments(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_consulting_payments_enrollment      ON consulting_payments(enrollment_id);
CREATE INDEX IF NOT EXISTS idx_consulting_objectives_enrollment    ON consulting_objectives(enrollment_id);
CREATE INDEX IF NOT EXISTS idx_consulting_private_notes_enrollment ON consulting_private_notes(enrollment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_consulting_session_reports_enrollment ON consulting_session_reports(enrollment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_consulting_assignments_enrollment   ON consulting_assignments(enrollment_id);

ALTER TABLE consulting_profiles        ENABLE ROW LEVEL SECURITY;
ALTER TABLE consulting_payments        ENABLE ROW LEVEL SECURITY;
ALTER TABLE consulting_objectives      ENABLE ROW LEVEL SECURITY;
ALTER TABLE consulting_private_notes   ENABLE ROW LEVEL SECURITY;
ALTER TABLE consulting_session_reports ENABLE ROW LEVEL SECURITY;

COMMIT;
