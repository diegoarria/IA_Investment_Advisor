#!/usr/bin/env python
"""
Nuvos ETF Phase 0 — dev-environment bootstrap helper.

Concatenates every backend/migrations/*.sql file, in the same numeric order
they were applied to production (by hand, in the Supabase SQL editor — there
is no automated migration runner in this repo; see check_migrations.py), into
one file: backend/scripts/dev_migration_bundle.sql.

This does NOT run anything against any database. It only reads the local
.sql files (no secrets in them) and writes a single concatenated file so a
brand-new, isolated dev Supabase project can be bootstrapped by pasting one
file into its SQL editor instead of pasting 122 files one at a time.

Usage:
    venv/bin/python scripts/build_dev_migration_bundle.py
"""
import re
from pathlib import Path

MIGRATIONS_DIR = Path(__file__).resolve().parent.parent / "migrations"
OUT_FILE = Path(__file__).resolve().parent / "dev_migration_bundle.sql"


def main() -> int:
    files = sorted(
        MIGRATIONS_DIR.glob("*.sql"),
        key=lambda p: (int(re.match(r"(\d+)", p.name).group(1)), p.name),
    )
    if not files:
        print("No .sql files found under migrations/ — check MIGRATIONS_DIR.")
        return 1

    with OUT_FILE.open("w") as out:
        out.write(
            "-- Nuvos dev-environment migration bundle — generated by "
            "scripts/build_dev_migration_bundle.py\n"
            "-- Paste this whole file into a NEW, isolated Supabase project's "
            "SQL editor.\n"
            "-- NEVER run this against the production project.\n\n"
        )
        for f in files:
            out.write(f"\n-- ===== {f.name} =====\n")
            out.write(f.read_text())
            out.write("\n")

    print(f"Wrote {len(files)} migrations ({sum(f.stat().st_size for f in files)} bytes) to {OUT_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
